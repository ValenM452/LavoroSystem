import { describe, expect, it } from 'vitest';
import { normalizePhone } from '../src/lib/phone';

describe('normalizePhone', () => {
  it.each([
    // Casos pedidos en T08
    ['03825 15-529781', '5493825529781'],
    ['3825529781', '5493825529781'],
    ['+54 9 3825 529781', '5493825529781'],
    // Variantes comunes
    ['(03825) 15 529781', '5493825529781'],
    ['3825 15529781', '5493825529781'],
    ['382515529781', '5493825529781'],
    ['5493825529781', '5493825529781'],
    ['+54 3825 15 529781', '5493825529781'],
    ['0054 9 3825 529781', '5493825529781'],
    ['03825529781', '5493825529781'],
    ['11 15 2345-6789', '5491123456789'],
    ['011 15 2345 6789', '5491123456789'],
    ['0351 15 612-3456', '5493516123456'],
    ['351 6123456', '5493516123456'],
  ])('%s → %s', (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it.each(['', 'abc', '529781', '3825 52978', '38255297811234', '0800 333 1234 5'])('rechaza %j', (input) => {
    expect(normalizePhone(input)).toBeNull();
  });
});
